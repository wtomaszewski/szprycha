import { existsSync, globSync, readFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { z } from 'zod';

const entrySchema = z.strictObject({
  coordinate: z.string().min(1),
  version: z.string().min(1),
  scope: z.enum(['runtime', 'transitive', 'build']),
  resolvedVersion: z.string().min(1).optional(),
  licenses: z.array(z.string().min(1)).min(1).or(z.null()),
  source: z.url({ protocol: /^https$/ }),
  review: z.string().min(1).optional(),
});
const manifestSchema = z.strictObject({
  androidReleaseReviewed: z.boolean(),
  dependencies: z.array(entrySchema).min(1),
});

const gradleExcludes = ['**/.gradle', '**/build'];
const spmFile = 'ios/App/CapApp-SPM/Package.swift';
const generatedCordova = ':capacitor-cordova-android-plugins';

function stripComments(source: string) {
  return source.replace(/\/\*[\s\S]*?\*\/|^\s*\/\/.*$/gm, '');
}

function gradleDeclarations(
  source: string,
  variables: ReadonlyMap<string, string>,
  installedCapacitor: boolean,
) {
  const declarations: Array<{ coordinate: string; version?: string }> = [];
  for (const [, configuration, expression = ''] of stripComments(
    source,
  ).matchAll(
    /(?:^|[;{])[ \t]*(classpath|(?!(?:test|androidTest)\w)(?:\w+)?(?:[Ii]mplementation|[Aa]pi|[Rr]untimeOnly|[Cc]ompileOnly))\b(?![ \t]*=)[ \t]*([^\n;]+)/gm,
  )) {
    // The npm package also declares build/publishing tooling in its own script.
    if (installedCapacitor && configuration === 'classpath') continue;
    const project = expression.match(
      /\bproject\s*\(\s*(?:path:\s*)?['"](:[^'"]+)['"]/,
    );
    const maven = expression.match(/['"]([\w.-]+:[\w.-]+):([^'"]+)['"]/);
    if (project?.[1]) {
      declarations.push({ coordinate: project[1] });
    } else if (maven?.[1] && maven[2]) {
      const [, coordinate, requested] = maven;
      const variable = requested.match(
        /^\$(?:\{(?:rootProject\.ext\.)?(\w+)\}|(\w+))$/,
      );
      const version = variable
        ? variables.get(variable[1] ?? variable[2] ?? '')
        : requested;
      declarations.push({ coordinate, version });
    } else if (!/^\(?\s*fileTree\(/.test(expression)) {
      throw new Error(
        `Unsupported Gradle dependency declaration: ${expression}`,
      );
    }
  }
  return declarations;
}

function spmDeclarations(source: string, file: string) {
  const declarations: Array<{ coordinate: string; version?: string }> = [];
  // CapApp-SPM is generated by Capacitor using exact versions and local npm paths.
  for (const [, declaration = ''] of stripComments(source).matchAll(
    /\.package\s*\(([^)]*)\)/g,
  )) {
    const remote = declaration.match(
      /^\s*url:\s*"([^"]+)"\s*,\s*exact:\s*"([^"]+)"\s*$/,
    );
    const local = declaration.match(
      /^\s*(?:name:\s*"[^"]+"\s*,\s*)?path:\s*"([^"]+)"\s*$/,
    );
    if (remote?.[1] && remote[2]) {
      declarations.push({ coordinate: remote[1], version: remote[2] });
    } else if (local?.[1]) {
      declarations.push({
        coordinate:
          'npm:' +
          relative('.', resolve(dirname(file), local[1])).replace(
            /^node_modules\//,
            '',
          ),
      });
    } else {
      throw new Error(`Unsupported Swift package declaration: ${declaration}`);
    }
  }
  return declarations;
}

function checkGradleReport(
  report: string,
  expected: ReadonlyMap<string, string>,
) {
  if (
    !/^releaseRuntimeClasspath\b/m.test(report) ||
    /\bFAILED\b/.test(report)
  ) {
    return ['Expected a fully resolved Gradle releaseRuntimeClasspath report'];
  }
  const actual = new Map<string, string>();
  const dependencies = report
    .split('\n')
    .filter((line) => !line.trimEnd().endsWith(' (c)'))
    .join('\n');
  for (const [
    ,
    requested = '',
    version = '',
    selected,
  ] of dependencies.matchAll(
    /(?:\+---|\\---) ([\w.-]+:[\w.-]+)(?::([^\s]+))?(?: -> ([^\s]+))?/g,
  )) {
    if (selected?.includes(':')) {
      const [group, artifact, replacement] = selected.split(':');
      if (replacement) actual.set(`${group}:${artifact}`, replacement);
    } else {
      actual.set(requested, selected ?? version);
    }
  }

  return [
    ...[...actual]
      .filter(([coordinate, version]) => expected.get(coordinate) !== version)
      .map(
        ([coordinate, version]) =>
          `Gradle resolved ${coordinate}:${version}; manifest has ${expected.get(coordinate) ?? 'no entry'}`,
      ),
    ...[...expected.keys()]
      .filter((coordinate) => !actual.has(coordinate))
      .map(
        (coordinate) =>
          `${coordinate} is in the manifest but absent from the Gradle report`,
      ),
  ];
}

export function auditNativeLicenses(
  root: string,
  allowed: ReadonlySet<string>,
  {
    strict = false,
    gradleReport,
  }: { strict?: boolean; gradleReport?: string } = {},
) {
  const read = (file: string) => readFileSync(resolve(root, file), 'utf8');
  const { dependencies, androidReleaseReviewed } = manifestSchema.parse(
    JSON.parse(read('licenses/native-deps.json')),
  );
  const { packages } = JSON.parse(read('package-lock.json')) as {
    packages: Record<string, { version: string }>;
  };
  const npmVersion = (path: string) =>
    packages[`node_modules/${path}`]?.version;

  const errors: string[] = [];
  const warnings: string[] = [];
  const pendingReview = strict ? errors : warnings;
  const entries = new Map<string, (typeof dependencies)[number]>();
  for (const entry of dependencies) {
    const { coordinate, licenses, review } = entry;
    if (entries.has(coordinate))
      errors.push(`Duplicate manifest entry: ${coordinate}`);
    entries.set(coordinate, entry);
    if (review || licenses === null) {
      pendingReview.push(`${coordinate}: ${review ?? 'license needs review'}`);
    }
    for (const license of licenses ?? []) {
      if (!allowed.has(license)) {
        errors.push(
          `${coordinate}: ${license} is outside the approved license list`,
        );
      }
    }
  }

  const variables = new Map(
    [
      ...stripComments(read('android/variables.gradle')).matchAll(
        /^\s*(\w+)\s*=\s*['"]([^'"]+)['"]/gm,
      ),
    ].map(([, name = '', version = '']) => [name, version]),
  );
  const projects = new Map<string, string>([
    [generatedCordova, '@capacitor/cli'],
  ]);
  for (const [, project = '', pkg = ''] of stripComments(
    read('android/capacitor.settings.gradle'),
  ).matchAll(
    /project\(['"](:[^'"]+)['"]\)\.projectDir\s*=\s*new File\(['"]\.\.\/node_modules\/(@[^/]+\/[^/'"]+)/g,
  )) {
    projects.set(project, pkg);
  }

  const gradleFiles = globSync('android/**/*build.gradle', {
    cwd: root,
    exclude: gradleExcludes,
  }).sort();
  // Capacitor's Android module declares AndroidX and Cordova dependencies of its own.
  const capacitorGradle =
    'node_modules/@capacitor/android/capacitor/build.gradle';
  gradleFiles.push(capacitorGradle);
  const observed = new Set<string>();
  function check(file: string, coordinate: string, version?: string) {
    observed.add(coordinate);
    const entry = entries.get(coordinate);
    if (!entry || entry.scope === 'transitive') {
      errors.push(
        `${file}: missing native manifest declaration for ${coordinate}`,
      );
    } else if (!version || entry.version !== version) {
      errors.push(
        `${file}: ${coordinate} requires ${version ?? 'a known version'}; manifest has ${entry.version}`,
      );
    }
  }

  for (const file of gradleFiles) {
    for (const { coordinate, version } of gradleDeclarations(
      read(file),
      variables,
      file === capacitorGradle,
    )) {
      const pkg = projects.get(coordinate);
      check(file, coordinate, pkg ? npmVersion(pkg) : version);
    }
  }
  for (const { coordinate, version } of spmDeclarations(
    read(spmFile),
    spmFile,
  )) {
    check(
      spmFile,
      coordinate,
      coordinate.startsWith('npm:') ? npmVersion(coordinate.slice(4)) : version,
    );
  }
  for (const file of globSync('android/**/*.{jar,aar}', {
    cwd: root,
    exclude: [...gradleExcludes, 'android/gradle/wrapper/gradle-wrapper.jar'],
  })) {
    errors.push(`${file}: bundled native archive requires a license review`);
  }
  for (const { coordinate, scope } of dependencies) {
    if (scope !== 'transitive' && !observed.has(coordinate)) {
      errors.push(
        `${coordinate}: manifest entry has no matching native declaration`,
      );
    }
  }

  if (!androidReleaseReviewed) {
    pendingReview.push(
      'Gradle releaseRuntimeClasspath transitive dependencies still need review',
    );
  }
  if (gradleReport !== undefined) {
    const release = dependencies.filter(
      ({ coordinate, scope }) =>
        scope !== 'build' &&
        /^[\w.-]+:[\w.-]+$/.test(coordinate) &&
        !coordinate.startsWith('npm:'),
    );
    errors.push(
      ...checkGradleReport(
        gradleReport,
        new Map(
          release.map(({ coordinate, version, resolvedVersion }) => [
            coordinate,
            resolvedVersion ?? version,
          ]),
        ),
      ),
    );
  }

  return { dependencies, errors: [...new Set(errors)], warnings };
}

export function buildNativeNotices(root: string, allowed: ReadonlySet<string>) {
  const { dependencies, errors } = auditNativeLicenses(root, allowed);
  if (errors.length) throw new Error(errors.join('\n'));

  const entries = dependencies
    .filter(({ scope }) => scope !== 'build')
    .map(
      ({ coordinate, version, resolvedVersion, licenses, source }) =>
        `${coordinate} @ ${resolvedVersion ?? version} (${licenses?.join(', ') ?? 'Pending license review'})\n${source}`,
    );
  const attributions = readFileSync(
    resolve(root, 'assets/licenses/mobile.txt'),
    'utf8',
  ).trimEnd();
  return ['THIRD_PARTY_NOTICES_MOBILE', ...entries, attributions].join('\n\n');
}

export function nativeLicensesPresent(root: string) {
  return ['android', 'ios', 'licenses/native-deps.json'].some((path) =>
    existsSync(resolve(root, path)),
  );
}
